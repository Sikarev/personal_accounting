/** Тип словаря без литеральных значений: другой язык обязан иметь те же ключи. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => infer R
    ? (...args: A) => R
    : { readonly [K in keyof T]: Widen<T[K]> }

export type Messages = Widen<typeof ru>
